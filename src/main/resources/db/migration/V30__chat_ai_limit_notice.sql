-- =========================================================
-- V30__chat_ai_limit_notice.sql
-- AI 답변 한도 소진 안내 문구 교체
-- =========================================================
--
-- V28에서 넣어둔 문구는 "AI 1회 답변" 정책에 맞춰 쓴 것이었다.
-- 한도가 3회로 늘고, 마지막 답변 뒤에 자동 답변을 닫는 정책으로 바뀌면서
-- 사용자에게 알려야 할 내용이 달라졌다.
--
--   (전) "상담사가 답변을 준비하고 있어요. 답변이 도착하면 이어서 문의하실 수 있어요."
--        → 상담사가 이미 보고 있다는 뉘앙스라, 실제로는 대기열에만 올라간 상태와 어긋난다.
--
--   (후) 자동 답변이 끝났다는 사실 + 사람 답변은 시간이 걸릴 수 있다는 예고.
--        기다림의 이유와 예상을 함께 줘야 사용자가 창을 닫고 기다릴 수 있다.
--        (기다리는 시간 자체보다, 얼마나 기다려야 할지 모르는 상태가 더 나쁘다.)
--
-- 운영자가 관리자 화면에서 언제든 고칠 수 있는 값이다. 여기 있는 건 초기값일 뿐이다.

UPDATE `chat_setting`
   SET `setting_value` = '자동 답변은 여기까지 도와드릴 수 있어요.\n남겨주신 내용은 상담사에게 전달했고, 확인 후 이 창으로 답변드릴게요. 상담사 답변까지는 시간이 걸릴 수 있어요.',
       `description` = 'AI 답변 한도를 모두 쓴 뒤 안내 문구(이 문구 뒤로 입력이 잠긴다)'
 WHERE `setting_key` = 'AI_LIMIT_NOTICE';
