-- AI가 답변하지 않고 상담사에게 넘길 때의 안내 문구 추가
-- =========================================================
--
-- 지금까지 이 경로는 화면에 아무것도 남기지 않았다. AI가 이관을 선택하거나(환불·계정
-- 문의처럼 지어내면 위험한 주제, 참고 정보로 답할 수 없는 질문) 호출이 실패하면
-- 답변만 없이 조용히 끝났다.
--
-- 그런데 이때 대화 상태는 WAITING_AGENT로 남고, 이 상태는 입력을 잠그지 않는다.
-- 즉 사용자는 "입력창은 열려 있는데 답은 안 오는" 화면을 본다. 이유를 모르니 같은 질문을
-- 다시 보내고, 그 시도가 시간당 한도를 갉아먹어 결국 남은 답변 기회까지 잃는다.
--
-- 안내 한 줄로 끊어준다. 답변이 없는 대신 무엇을 기다리면 되는지 알려주면, 사용자는
-- 창을 닫고 기다릴 수 있다.
--
-- AI_LIMIT_NOTICE와 다른 문구인 이유: 그쪽은 "자동 답변을 다 썼고 이제 입력이 잠긴다"는
-- 종료 안내다. 여기는 자동 답변 기회가 아직 남아 있고 입력도 열려 있다.
--
-- 운영자가 관리자 화면에서 언제든 고칠 수 있는 값이다. 여기 있는 건 초기값일 뿐이다.

INSERT INTO `chat_setting` (`setting_key`, `setting_value`, `description`)
VALUES ('AI_ESCALATE_NOTICE',
        '이 문의는 상담사가 확인하는 편이 정확해요. 남겨주신 내용은 전달했고, 확인 후 이 창으로 답변드릴게요.',
        'AI가 답변하지 않고 상담사에게 넘길 때 안내 문구(입력은 잠기지 않는다)');
