-- DB에 들어간 사용자 노출 문구의 용어를 표준어로 맞춘다(docs/terminology-glossary.md).
-- =========================================================
--
-- 코드의 한글 문구는 파일을 고치면 끝나지만, 시딩으로 DB에 들어간 문구는 그렇지 않다.
-- V28(chat_menu)과 V39(feedback_tags)가 넣은 값은 지금도 화면에 그대로 나오는데,
-- 거기에 "박람회", "페어업체"가 남아 있어 코드 쪽 "행사", "행사 관리자"와 어긋난다.
--
-- 이미 적용된 마이그레이션 파일을 고치지 않는 이유: Flyway가 체크섬을 검증해서 기동 자체가
-- 막힌다. 그래서 새 버전에서 UPDATE로 덮는다.
--
-- 버전이 50인 이유: 운영에 49까지 적용돼 있다. out-of-order는 application.yaml에서 꺼둔
-- 값이라(V48 주석 참고) 반드시 마지막 번호보다 커야 한다.
--
-- 통째로 새 문구를 쓰지 않고 REPLACE로 단어만 바꾸는 이유: 이 문구들은 운영자가 관리자
-- 화면에서 고칠 수 있는 값이다(V28 주석). 통째 UPDATE는 운영자가 다듬어 둔 카피를 조용히
-- 되돌린다. 단어 치환이면 고쳐 쓴 문장에서도 용어만 바뀐다.

-- ---------------------------------------------------------
-- 1) 상담 고정 답변 메뉴 (chat_menu, V28 시딩)
-- ---------------------------------------------------------
-- '2. 페어업체 문의'는 행사를 여는 쪽의 문의 창구다. 그 역할의 표준 호칭이 "행사 관리자"라
-- 라벨도 거기에 맞춘다 - 옆에 있는 '1. 참가업체 문의'와 짝이 맞아야 무엇을 고르는 메뉴인지
-- 읽힌다.
UPDATE `chat_menu`
SET `label` = REPLACE(`label`, '페어업체', '행사 관리자')
WHERE `label` LIKE '%페어업체%';

UPDATE `chat_menu`
SET `fixed_answer` = REPLACE(REPLACE(`fixed_answer`, '페어업체', '행사 관리자'), '박람회', '행사')
WHERE `fixed_answer` LIKE '%페어업체%'
   OR `fixed_answer` LIKE '%박람회%';

-- ---------------------------------------------------------
-- 2) 리뷰 태그 (feedback_tags, V39 시딩)
-- ---------------------------------------------------------
-- '박람회 특가·혜택이 좋아요' 한 건. 리뷰 작성 화면에서 관람객이 직접 고르는 문구다.
-- tag_id를 그대로 두므로 이미 이 태그를 고른 리뷰(booth_feedback_selections)는 영향이 없다.
UPDATE `feedback_tags`
SET `label` = REPLACE(`label`, '박람회', '행사')
WHERE `label` LIKE '%박람회%';
