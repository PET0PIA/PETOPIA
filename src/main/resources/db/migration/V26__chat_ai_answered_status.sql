-- =========================================================
-- V26__chat_ai_answered_status.sql
-- 상담 대화에 AI_ANSWERED 상태 추가
-- =========================================================
--
-- 왜 상태를 하나 더 두는가
--
-- V25에서는 status가 두 가지 일을 겸했다.
--   (1) 대기열 상태  - 상담사가 답해야 하는 대화인가
--   (2) 잠금 여부    - 사용자가 지금 메시지를 더 보낼 수 있는가
--
-- 둘을 WAITING_AGENT 하나로 표현하다 보니, 질문을 보내기만 해도 입력이 잠겼다.
-- 그런데 잠금의 원래 목적은 "AI가 1회 답했으니 이제 사람이 이어받을 차례"를 지키는
-- 것이지, 답변을 기다리는 모든 사용자를 막는 게 아니다. AI가 답하지 않은 대화
-- (상담사 연결 유형, 운영시간 내, AI가 답변을 넘긴 경우)까지 잠그면 사용자는
-- 추가 설명을 덧붙일 수도, 오타를 정정할 수도 없다.
--
-- 그래서 상태를 나눈다.
--   WAITING_AGENT - 상담사 답변 대기. 입력 가능(계속 말을 보탤 수 있다)
--   AI_ANSWERED   - AI가 1회 답함. 상담사가 답할 때까지 입력 잠김
--
-- 컬럼 타입은 VARCHAR라 값 추가에 DDL 변경이 필요 없다. 다만 주석에 적힌 값 목록이
-- 실제와 어긋나면 다음 사람이 그 주석을 믿고 잘못 판단하므로 함께 고친다.

ALTER TABLE `chat_conversation`
    MODIFY COLUMN `status` VARCHAR(20) NOT NULL DEFAULT 'BOT'
        COMMENT 'BOT | WAITING_AGENT | AI_ANSWERED | IN_PROGRESS | CLOSED (AI_ANSWERED만 입력 잠금)';
