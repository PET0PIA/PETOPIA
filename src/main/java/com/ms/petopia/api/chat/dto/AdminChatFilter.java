package com.ms.petopia.api.chat.dto;

/**
 * 상담사 대기열 필터.
 *
 * <p>상태(status)를 그대로 노출하지 않고 <b>상담사가 하는 일</b>로 묶는다. 내부 상태는 다섯
 * 가지지만 상담사에게 필요한 구분은 "내가 들고 있는 것 / 자동 응대로 끝난 것 / 끝난 것"이다.
 * 상태별로 탭을 쪼개면 여러 목록을 번갈아 확인해야 하고, 그러다 한쪽을 놓친다.
 */
public enum AdminChatFilter {

    /**
     * 아직 끝나지 않아 상담사가 들고 있는 상담(기본값).
     *
     * <p>답변을 기다리는 것({@code WAITING_AGENT})과 이미 답해서 고객 반응을 기다리는
     * 것({@code IN_PROGRESS})을 함께 담는다. 후자를 따로 빼면, 고객이 답하지 않은 상담이
     * 다른 목록에서 잊힌 채 종료되지 않고 남는다. 급한 순서는 정렬이 책임진다 - 답변이
     * 필요한 건이 항상 위로 온다.
     *
     * <p><b>{@code AI_HANDLED}는 뺀다.</b> 운영시간 밖에 자동 응대로 마무리된 대화이고,
     * 사용자가 다시 물으면 그때 {@code WAITING_AGENT}로 돌아온다. 여기 섞으면 아침에 출근한
     * 상담사가 "밤새 쌓인 미답변"으로 읽고 이미 답이 나간 대화를 다시 붙잡는다.
     *
     * <p>{@code BOT}도 뺀다 - 연결만 하고 질문하지 않은 대화라 답할 내용이 없다.
     */
    OPEN,

    /**
     * 운영시간 밖에 AI가 응대한 상담.
     *
     * <p>대기열에서 빼는 대신 볼 수 있는 자리를 남긴다. "AI가 밤에 뭐라고 답했는지"를
     * 확인할 곳이 없으면, 자동 응대는 아무도 검수하지 않는 채널이 된다.
     */
    AI_HANDLED,

    /** 종료된 상담. */
    CLOSED,

    /** 연결만 하고 끝난 것까지 포함한 전부. 이력 확인용. */
    ALL
}
