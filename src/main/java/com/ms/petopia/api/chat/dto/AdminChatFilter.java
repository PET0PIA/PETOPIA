package com.ms.petopia.api.chat.dto;

/**
 * 상담사 대기열 필터.
 *
 * <p>상태(status)를 그대로 노출하지 않고 <b>상담사가 하는 일</b>로 묶는다. 내부 상태는 다섯
 * 가지지만 상담사에게 필요한 구분은 "내가 들고 있는 것 / 끝난 것" 둘이다. 상태별로 탭을
 * 쪼개면 여러 목록을 번갈아 확인해야 하고, 그러다 한쪽을 놓친다.
 */
public enum AdminChatFilter {

    /**
     * 아직 끝나지 않아 상담사가 들고 있는 상담(기본값).
     *
     * <p>답변을 기다리는 것({@code WAITING_AGENT}, {@code AI_ANSWERED})과 이미 답해서 고객
     * 반응을 기다리는 것({@code IN_PROGRESS})을 함께 담는다. 후자를 따로 빼면, 고객이
     * 답하지 않은 상담이 다른 목록에서 잊힌 채 종료되지 않고 남는다. 급한 순서는 정렬이
     * 책임진다 - 답변이 필요한 건이 항상 위로 온다.
     *
     * <p>{@code BOT}은 뺀다 - 고정 답변만 보고 끝난 대화라 상담사가 할 일이 없다.
     * 이것들이 섞이면 대기열 건수가 실제 업무량과 어긋난다.
     */
    OPEN,

    /** 종료된 상담. */
    CLOSED,

    /** 봇 응대만 있었던 것까지 포함한 전부. 이력 확인용. */
    ALL
}
